val LocalStrings = compositionLocalOf { EnglishStrings }

fun stringsFor(language: LanguageSetting): Strings = when (language) {
    LanguageSetting.ENGLISH -> EnglishStrings
    LanguageSetting.RUSSIAN -> RussianStrings
    LanguageSetting.SYSTEM ->
        if (Locale.getDefault().language == "ru") RussianStrings else EnglishStrings
}
